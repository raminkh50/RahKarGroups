add_action('wp_ajax_rknm_add_all_to_cart_from_next_purchase', 'rknm_ajax_add_all_to_cart_from_next_purchase');
function rknm_ajax_add_all_to_cart_from_next_purchase() {
    check_ajax_referer('rknm_next_purchase_nonce', 'nonce');

    if (!is_user_logged_in()) {
        wp_send_json_error(['message' => 'لطفا ابتدا وارد حساب کاربری خود شوید.']);
        return;
    }

    $user_id = get_current_user_id();
    $next_purchase_list = get_user_meta($user_id, '_rknm_next_purchase_list', true);

    if (empty($next_purchase_list) || !is_array($next_purchase_list)) {
        wp_send_json_error(['message' => 'لیست خرید بعدی خالی است.']);
        return;
    }

    $original_next_purchase_list = $next_purchase_list;
    $success_count = 0;
    $error_count = 0;
    
    foreach ($original_next_purchase_list as $item) {
        $product_id   = isset($item['product_id']) ? intval($item['product_id']) : 0;
        $variation_id = isset($item['variation_id']) ? intval($item['variation_id']) : 0;
        $quantity     = isset($item['quantity']) ? intval($item['quantity']) : 1;
        $variation    = isset($item['variation']) ? $item['variation'] : [];

        $product_to_add = $variation_id > 0 ? wc_get_product($variation_id) : wc_get_product($product_id);
        if (!$product_to_add || !$product_to_add->is_purchasable()) {
            $error_count++;
            continue;
        }

        $cart_item_key = WC()->cart->add_to_cart($product_id, $quantity, $variation_id, $variation);

        if ($cart_item_key) {
            $success_count++;
            // Remove from next purchase list immediately after successful add
            $next_purchase_list_after_remove = rknm_remove_from_next_purchase($product_id, $variation_id, $user_id);
            if ($next_purchase_list_after_remove !== false) {
                $next_purchase_list = $next_purchase_list_after_remove;
            }
        } else {
            $error_count++;
        }
    }
    
    // After the loop, the $next_purchase_list is already updated
    update_user_meta($user_id, '_rknm_next_purchase_list', $next_purchase_list);

    $message = '';
    if ($success_count > 0) {
        $message = sprintf('%d محصول با موفقیت به سبد خرید اضافه شد.', $success_count);
        if ($error_count > 0) {
            $message .= sprintf(' %d محصول به دلیل خطا اضافه نشد.', $error_count);
        }
    } else {
        $message = 'هیچ محصولی به سبد خرید اضافه نشد.';
        if ($error_count > 0) {
            $message .= sprintf(' %d محصول به دلیل خطا قابل افزودن نبودند.', $error_count);
        }
    }

    // Capture the updated HTML for both tabs
    ob_start();
    cart_basket(WC()->cart, $count_cart=WC()->cart->get_cart_contents_count());
    $cart_html = ob_get_clean();

    ob_start();
    next_purchase($next_purchase_list, $count_cartnext=is_array($next_purchase_list) ? count($next_purchase_list) : 0);
    $next_purchase_html = ob_get_clean();

    wp_send_json_success([
        'message'        => $message,
        'cart_count'     => $count_cart,
        'nextcart_count' => $count_cartnext,
        'html_cart_basket' => $cart_html,
        'html_next_purchase' => $next_purchase_html,
    ]);
}
