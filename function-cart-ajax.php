// Functions for cart and next purchase AJAX functionality
// Helper function to check if product exists in next purchase list
function rknm_product_exists_in_next_purchase($product_id, $variation_id = 0, $user_id = null) {
    if (!$user_id)   $user_id = get_current_user_id();
    if (!$user_id)   return false;
    
    $next_purchase_list = get_user_meta($user_id, '_rknm_next_purchase_list', true);
    if (!is_array($next_purchase_list)) {
        return false;
    }
    foreach ($next_purchase_list as $item) {
        if ($item['product_id'] == $product_id && $item['variation_id'] == $variation_id) {
            return true;
        }
    }
    return false;
}

// Helper function to remove product from next purchase list
function rknm_remove_from_next_purchase($product_id, $variation_id = 0, $user_id = null) {
    if (!$user_id)  $user_id = get_current_user_id();
    if (!$user_id)  return false;
    
    $next_purchase_list = get_user_meta($user_id, '_rknm_next_purchase_list', true);
    
    if (!is_array($next_purchase_list))   return false;
    $removed = false;
    foreach ($next_purchase_list as $key => $item) {
        if ($item['product_id'] == $product_id && $item['variation_id'] == $variation_id) {
            unset($next_purchase_list[$key]);
            $removed = true;
            break;
        }
    }
    if ($removed) {
        update_user_meta($user_id, '_rknm_next_purchase_list', array_values($next_purchase_list));
        do_action('rknm_removed_from_next_purchase', $product_id, $user_id);
        return $next_purchase_list;
    }
    return false;
}
// Helper function del from cart
function rknm_helper_del_from_cart($cart_key,$product_id, $user_id,$next_purchase_list){
    $removed = WC()->cart->remove_cart_item($cart_key);

    if($removed) {
        if($next_purchase_list) do_action('rknm_added_to_next_purchase', $product_id, $user_id);

        // Capture the updated HTML for both tabs
        ob_start();
        cart_basket(WC()->cart, $count_cart=WC()->cart->get_cart_contents_count());
        $cart_html = ob_get_clean();

        if($next_purchase_list){
        ob_start();
        $next_purchase_list_updated = get_user_meta($user_id, '_rknm_next_purchase_list', true);
        next_purchase($next_purchase_list_updated, $count_cartnext=is_array($next_purchase_list_updated) ? count($next_purchase_list_updated) : 0);
        $next_purchase_html = ob_get_clean();
        $message_action='محصول به لیست خرید بعدی منتقل شد.';
        } else {
            $next_purchase_html= $count_cartnext=null;
            $message_action='محصول با موفقیت حذف شد.';
        }
        wp_send_json_success([
            'message' => $message_action,
            'cart_count' => $count_cart,
            'nextcart_count' => $count_cartnext,
            'html_cart_basket' => $cart_html,
            'html_next_purchase' => $next_purchase_html,
        ]);
        
        
    } else {
        // If removal failed, revert adding to next purchase list
        if($next_purchase_list){
         array_pop($next_purchase_list);
         update_user_meta($user_id, '_rknm_next_purchase_list', $next_purchase_list);
         wp_send_json_error(['message' => 'محصول ازسبد خرید حذف نشد.']);
        }
    }    
}

